def admin_routes():
    """`[(route, view_class)]` for every `api/v1/admin/…` URL, in resolver order."""
    out = []

    def walk(patterns, prefix):
        for p in patterns:
            if isinstance(p, URLResolver):
                walk(p.url_patterns, prefix + str(p.pattern))
            else:
                route = prefix + str(p.pattern)
                view = getattr(p.callback, 'view_class', None)
                if route.startswith('api/v1/admin/') and view is not None:
                    out.append((route, view))
    walk(get_resolver('halatuju.urls').url_patterns, '')
    return out


def _methods(view):
    return [m for m in ('get', 'post', 'patch', 'put') if hasattr(view, m)]


def _no_network(*args, **kwargs):
    raise OSError('team tables matrix: the network is cut')


