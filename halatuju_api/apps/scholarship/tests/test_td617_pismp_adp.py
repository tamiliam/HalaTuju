"""TD-617 owner ruling (2026-11-14, option 1): PISMP, the American Degree Program and MARA overseas
preparation.

A. PISMP stays a degree for the award and the funding estimate (RM2,000 either way). An SPM-route
   PISMP student (SPM only: the 1-year preparatory + 4-year degree is ONE programme) is never owed
   higher results, before or after submit. A PISMP student holding STPM / matric results keeps the
   checks. "Ijazah Sarjana Muda Pendidikan" at a university (UPSI) is an ordinary degree.
B. The American Degree Program (fully funded under MARA) and MARA's "Persediaan ... Luar Negara"
   (overseas study, not supported) get a RED pathway fact, `pathway_funded_or_abroad`, an award
   CONFIDENT_DISQUALIFIER. The amount is untouched; the reviewer decides.

Money: `MoneyPinnedToMain` compares the award amount and `funding_estimate.classify_pathway` for
every code x name x institution x results-held input against `fixtures/td617_money_pin.json`,
generated by running origin/main 66c58c607's code on the same inputs (2026-11-14).
"""
import json
import pathlib

from django.test import TestCase, override_settings

from apps.scholarship import award, higher_owed, results_route
from apps.scholarship.models import ScholarshipApplication
from apps.scholarship.tests.test_slip_check_matrix import (
    GENUINE, MATRIC_HELD, SPM_HELD, SPM_ROWS, STPM_HELD, SUBMITTED, UNSURE, _academic, _app, _doc, spm_read)
from apps.scholarship.verdict_engine import build_verdict

PIN = pathlib.Path(__file__).resolve().parent / 'fixtures' / 'td617_money_pin.json'

CODES = ('', 'pismp', 'stpm', 'matric', 'asasi', 'university', 'degree', 'mara', 'tvet_other', 'diploma', 'poly')
NAMES = ('', 'Program Ijazah Sarjana Muda Perguruan (PISMP)', 'Program Persediaan PISMP',
         'Ijazah Sarjana Muda Perguruan', 'Ijazah Sarjana Muda Pendidikan', 'American Degree Program',
         'American Degree Programme', 'American Degree Transfer Program', 'Degree Programme in Business',
         'Program Persediaan Ijazah Luar Negara', 'Program Persediaan Luar Negara', 'Tingkatan Enam',
         'Diploma Kejuruteraan Mekanikal')
INSTITUTIONS = ('', 'Institut Pendidikan Guru Kampus Ipoh', 'IPG Kampus Tuanku Bainun',
                'Universiti Pendidikan Sultan Idris', 'Majlis Amanah Rakyat (MARA)', 'Kolej Persediaan MARA')
HELD = (('spm', SPM_HELD), ('stpm', STPM_HELD))


def plan(code, name, institution='X'):
    return {'chosen_pathway': code, 'pathway_certainty': 'sure',
            'chosen_programme': {'course_name': name, 'institution': institution}}


def money_rows():
    """[held, code, name, institution, award, funding route] for every input, on one application per
    results-held profile (re-pointed in memory; the destination memo cleared each time)."""
    from apps.scholarship.funding_estimate import classify_pathway
    rows = []
    for held, profile in HELD:
        app = _app(profile, plan('', ''))
        for code in CODES:
            for name in NAMES:
                for inst in INSTITUTIONS:
                    app.chosen_pathway = code
                    app.chosen_programme = {'course_name': name, 'institution': inst}
                    app._results_destination = None
                    amount = award.proposed_award_amount(app)
                    rows.append([held, code, name, inst, None if amount is None else str(amount),
                                 classify_pathway(app)])
    return rows


class MoneyPinnedToMain(TestCase):
    def test_award_and_funding_route_equal_main_for_every_input(self):
        expected = json.loads(PIN.read_text(encoding='utf-8'))
        got = money_rows()
        self.assertEqual(len(got), len(CODES) * len(NAMES) * len(INSTITUTIONS) * len(HELD))
        self.assertEqual(len(expected), len(got))
        for want, have in zip(expected, got):
            self.assertEqual(have, want)


@override_settings(DOC_GENUINENESS_CHECK_ENABLED=True)
class PismpSpmRouteNeverOwed(TestCase):
    #: Degree-bound on origin/main (by name or by code), so owed and capped there.
    SPM_ROUTE = (('pismp', 'Ijazah Sarjana Muda Pendidikan', 'X'),
                 ('degree', 'Program Ijazah Sarjana Muda Perguruan', 'IPG Kampus Ipoh'),
                 ('university', 'Ijazah Sarjana Muda Pendidikan', 'Institut Pendidikan Guru Kampus Ipoh'),
                 ('degree', 'Program Persediaan PISMP', 'X'))

    def test_spm_route_pismp_is_not_owed_after_submit(self):
        for code, name, inst in self.SPM_ROUTE:
            with self.subTest(code=code, name=name, inst=inst):
                app = _app(SPM_HELD, plan(code, name, inst), SUBMITTED)
                _doc(app, 'results_slip', spm_read(SPM_ROWS), GENUINE)
                app = ScholarshipApplication.objects.get(pk=app.pk)
                self.assertTrue(results_route.degree_bound(app))     # still a degree for money
                self.assertTrue(results_route.is_pismp(app))
                self.assertFalse(higher_owed.undeclared(app))
                self.assertEqual(higher_owed.owed_kind(app), '')
                self.assertEqual(higher_owed.ask_codes(app), set())
                codes = {i['code'] for i in _academic(app)['unresolved']}
                self.assertFalse(codes & {'higher_results_not_declared', 'higher_results_not_on_file'})

    def test_spm_route_pismp_is_not_asked_before_submit(self):
        for code, name, inst in self.SPM_ROUTE:
            with self.subTest(code=code, name=name, inst=inst):
                self.assertEqual(results_route.higher_need(_app(SPM_HELD, plan(code, name, inst))), '')


@override_settings(DOC_GENUINENESS_CHECK_ENABLED=True)
class PismpHigherRouteKeepsTheChecks(TestCase):
    def test_stpm_or_matric_holder_on_pismp_is_still_checked_after_submit(self):
        for profile, kind in ((STPM_HELD, 'stpm'), (MATRIC_HELD, 'matric')):
            with self.subTest(kind):
                app = _app(profile, plan('pismp', 'Ijazah Sarjana Muda Pendidikan', 'IPG Kampus Ipoh'), SUBMITTED)
                self.assertTrue(results_route.is_pismp(app))
                self.assertTrue(higher_owed._needs_higher(app))
                self.assertEqual(higher_owed.declared_kind(app), kind)

    def test_legacy_entered_stpm_grades_on_pismp_are_still_checked(self):
        # Results recorded as SPM, STPM grades entered: she DECLARED STPM results - not the SPM route.
        legacy = {**SPM_HELD, 'stpm_grades': STPM_HELD['stpm_grades'], 'stpm_cgpa': 3.67}
        app = _app(legacy, plan('pismp', 'Ijazah Sarjana Muda Pendidikan'), SUBMITTED)
        self.assertEqual(higher_owed.declared_kind(app), 'stpm')
        self.assertTrue(higher_owed._needs_higher(app))


@override_settings(DOC_GENUINENESS_CHECK_ENABLED=True)
class UniversityPendidikanUnchanged(TestCase):
    """'Pendidikan' alone is not PISMP: a university education degree keeps origin/main's rules."""
    UPSI = (('stpm', 'Ijazah Sarjana Muda Pendidikan', 'Universiti Pendidikan Sultan Idris'),
            ('university', 'Ijazah Sarjana Muda Pendidikan', 'Universiti Pendidikan Sultan Idris'),
            ('', 'Ijazah Sarjana Muda Pendidikan (Bahasa Tamil)', 'Universiti Malaya'))

    def test_asked_before_submit_and_owed_after(self):
        for code, name, inst in self.UPSI:
            with self.subTest(code=code, inst=inst):
                self.assertFalse(results_route.is_pismp(_app(SPM_HELD, plan(code, name, inst))))
                self.assertEqual(results_route.higher_need(_app(SPM_HELD, plan(code, name, inst))),
                                 'required_with_slip')
                app = _app(SPM_HELD, plan(code, name, inst), SUBMITTED)
                _doc(app, 'results_slip', spm_read(SPM_ROWS), GENUINE)
                app = ScholarshipApplication.objects.get(pk=app.pk)
                self.assertTrue(higher_owed.undeclared(app))
                fact = _academic(app)
                self.assertEqual(fact['status'], UNSURE)
                self.assertIn('higher_results_not_declared', {i['code'] for i in fact['unresolved']})


class FundedOrAbroadIsRed(TestCase):
    RED = (('tvet_other', 'American Degree Program'), ('', 'American Degree Programmes'),
           ('university', 'AMERICAN  DEGREE PROGRAMME (ADP)'),
           ('mara', 'Program Persediaan Ijazah Luar Negara'), ('', 'Program Persediaan Luar Negara (MARA)'))
    NOT_RED = (('tvet_other', 'American Degree Transfer Program'), ('', 'Degree Programme in Business'),
               ('', "Bachelor's Degree Programme in Accounting"), ('mara', 'Program Persediaan Ijazah'),
               ('', 'Ijazah Sarjana Muda Pendidikan'))

    def _pathway(self, app):
        return next(f for f in build_verdict(app) if f['fact'] == 'pathway')

    def test_adp_and_mara_overseas_preparation_are_a_red_disqualifier(self):
        for code, name in self.RED:
            with self.subTest(name):
                app = _app(SPM_HELD, plan(code, name, 'Kolej MARA Banting'))
                fact = self._pathway(app)
                self.assertEqual(fact['status'], 'gap')
                self.assertIn('pathway_funded_or_abroad', {i['code'] for i in fact['unresolved']})
                self.assertEqual(award.verdict_disqualifier(build_verdict(app)), 'pathway_funded_or_abroad')
                self.assertEqual(str(award.proposed_award_amount(app)), '2000')   # amount untouched

    def test_adtp_plain_degree_programme_and_the_institution_alone_are_not(self):
        for code, name in self.NOT_RED:
            with self.subTest(name):
                app = _app(SPM_HELD, plan(code, name, 'Kolej Persediaan MARA, Luar Negara'))
                codes = {i['code'] for i in self._pathway(app)['unresolved']}
                self.assertNotIn('pathway_funded_or_abroad', codes)
                self.assertEqual(award.verdict_disqualifier(build_verdict(app)), '')

    def test_a_clean_pathway_fact_turns_red(self):
        from apps.scholarship.verdict_pathway import funded_or_abroad
        app = _app(SPM_HELD, plan('tvet_other', 'American Degree Program'))
        fact = funded_or_abroad(app, {'fact': 'pathway', 'status': 'verified', 'evidence': [], 'unresolved': []})
        self.assertEqual(fact['status'], 'gap')
        self.assertEqual(fact['unresolved'], [{'code': 'pathway_funded_or_abroad',
                                               'params': {'programme': 'American Degree Program'}}])
