/**
 * `npm run mobile-ledger` — writes `docs/mobile-ledger.md` (Mobile M0).
 *
 * The ledger is GENERATED, never edited by hand: one row per route from `src/lib/mobileClass.ts`
 * (its class and the sprint that fixes or gates it), joined to `mobile-check/baseline.json` (the
 * worst number over every measured cell). Run it after `npm run mobile-check -- --update` and
 * commit both files together.
 *
 * Node loads `mobileClass.ts` directly (type stripping, Node 22.6+; the repo is on 24), which is
 * why that file keeps to plain data. The output is deterministic — no clock — so a re-run with no
 * change writes the same bytes.
 */
import * as fs from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'
import { MOBILE_CLASS } from '../src/lib/mobileClass.ts'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT = path.resolve(HERE, '..', '..', 'docs', 'mobile-ledger.md')
const baseline = JSON.parse(fs.readFileSync(path.join(HERE, 'baseline.json'), 'utf8'))
const cells = baseline.cells

/** Every baseline cell for an id (`/route` or `sandbox:slug`), as [key, numbers]. */
const cellsOf = (id) => Object.entries(cells).filter(([k]) => k.slice(0, k.lastIndexOf(' @')) === id)

function worst(entries) {
  const pick = (n) => Math.max(0, ...entries.map(([, c]) => c[n]))
  return { overflow: pick('overflow'), smallInputs: pick('smallInputs'), smallTargets: pick('smallTargets') }
}
const clean = (w) => w.overflow === 0 && w.smallInputs === 0 && w.smallTargets === 0
const CLASS_LABEL = { must: 'Must', can: 'Can', desktop: 'Desktop-only' }

const rows = []
const tally = { must: 0, can: 0, desktop: 0, measured: 0, green: 0 }
for (const [route, e] of Object.entries(MOBILE_CLASS).sort(([a], [b]) => a.localeCompare(b))) {
  tally[e.cls]++
  const sources = []
  const measured = []
  if (e.visit && cellsOf(route).length) { sources.push('public page'); measured.push(...cellsOf(route)) }
  for (const s of e.surfaces ?? []) {
    if (cellsOf(`sandbox:${s}`).length) { sources.push(`sandbox \`${s}\``); measured.push(...cellsOf(`sandbox:${s}`)) }
  }
  let status
  let numbers = ['—', '—', '—']
  const notes = []
  if (e.redirect) notes.push(`redirects to \`${e.redirect}\``)
  if (e.cls === 'desktop') notes.push(e.why)
  if (measured.length) {
    const w = worst(measured)
    numbers = [`${w.overflow}`, `${w.smallInputs}`, `${w.smallTargets}`]
    status = clean(w) ? '✅' : '❌'
    tally.measured++
    if (clean(w)) tally.green++
  } else if (e.redirect) {
    status = 'n/a (redirect only)'
  } else if (e.cls === 'desktop') {
    status = `not yet measurable — desktop-only panel due ${e.sprint}`
  } else {
    status = `not yet measurable — signed-in, no sandbox surface yet (${e.sprint})`
  }
  const cellsNote = measured.length ? `${measured.length} (${sources.join(', ')})` : '—'
  rows.push(`| \`${route}\` | ${CLASS_LABEL[e.cls]} | ${e.sprint} | ${cellsNote} | ${numbers.join(' | ')} | ${status} | ${notes.join('; ')} |`)
}

// Surfaces measured but not tied to one route (component galleries).
const tied = new Set(Object.values(MOBILE_CLASS).flatMap((e) => e.surfaces ?? []))
const loose = [...new Set(Object.keys(cells).filter((k) => k.startsWith('sandbox:'))
  .map((k) => k.slice('sandbox:'.length, k.lastIndexOf(' @'))))].filter((s) => !tied.has(s)).sort()
const looseRows = loose.map((s) => {
  const w = worst(cellsOf(`sandbox:${s}`))
  return `| \`${s}\` | ${cellsOf(`sandbox:${s}`).length} | ${w.overflow} | ${w.smallInputs} | ${w.smallTargets} | ${clean(w) ? '✅' : '❌'} |`
})

const m = baseline.measured ?? {}
const total = Object.keys(MOBILE_CLASS).length
const md = `# Mobile ledger

> **Generated by \`npm run mobile-ledger\` — do not edit.** Classes live in
> \`halatuju-web/src/lib/mobileClass.ts\`; numbers in \`halatuju-web/mobile-check/baseline.json\`.
> The rules are in [mobile-standard.md](mobile-standard.md).

Baseline last updated **${m.updated ?? 'never'}** · public pages measured from \`${m.public ?? '—'}\`${/localhost|127\.0\.0\.1/.test(m.public ?? '') ? ' (this branch, live API data)' : ''} ·
sandbox surfaces from \`${m.sandbox ?? '—'}\` · widths 360 and 390 px · English, Malay and Tamil.

**${total} routes:** ${tally.must} Must · ${tally.can} Can · ${tally.desktop} Desktop-only.
**${tally.measured} measured** (public page or sandbox surface), **${tally.green} fully green.**

How to read a row: the three numbers are the WORST over every measured cell (width × language, and
every sandbox surface that mounts the screen) — sideways scroll in CSS px, text fields under 16 px,
controls under 44 × 44 px. ✅ means all three are 0. "Not yet measurable" means the check cannot
reach the screen yet: it never signs in, so a signed-in screen is measured only once a sandbox
surface mounts it — the sprint named is the one that fixes it and adds that surface.

| Route | Class | Sprint | Cells measured | Overflow px | Small fields | Small targets | Status | Notes |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## Sandbox surfaces not tied to one route

Component galleries — measured, but no single route is "them".

| Surface | Cells | Overflow px | Small fields | Small targets | Status |
|---|---|---|---|---|---|
${looseRows.join('\n') || '| — | | | | | |'}
`
fs.writeFileSync(OUT, md)
console.log(`mobile-ledger: wrote ${path.relative(process.cwd(), OUT)} — ${total} routes, ${tally.measured} measured, ${tally.green} green.`)
